'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict'),vm=require('node:vm');
const bank=JSON.parse(fs.readFileSync('exam_questions.json','utf8'));
const app=fs.readFileSync('app.js','utf8'),sw=fs.readFileSync('sw.js','utf8');
const audit=JSON.parse(fs.readFileSync('editorial/task1-v188-school-pure-scope-correction.json','utf8'));
const fn=app.match(/function mockEligibleQuestion\(q\)\{[\s\S]*?\n\}/);
assert(fn,'Maths school-mock scope function missing');
const eligible=vm.runInNewContext(fn[0]+'\nmockEligibleQuestion');
assert.equal(bank.bankVersion,70);
assert.equal(bank.questions.length,1268);
const target=bank.questions.find(q=>q.id==='orig_v31_maths_proof_2');
assert(target,'Original contradiction question must remain in the general bank');
assert.equal(target.level,'A-level');
assert.equal(target.mock,false);
assert.equal(target.marks,3);
assert.match(target.prompt,/proof by contradiction/);
assert.equal(target.markPoints.length,3);
assert.equal(eligible(target),false);
const selected=bank.questions.filter(q=>q.subject==='Maths'&&eligible(q));
assert.equal(selected.length,128);
assert(selected.every(q=>q.level==='AS'&&q.mock===true));
assert(!selected.some(q=>/proof by contradiction/i.test(q.prompt)));
assert(eligible({subject:'Maths',mock:true,level:'AS',topic:'Proof',prompt:'Disprove by counterexample'}));
assert(eligible({subject:'Chemistry',mock:true,level:'A2',topic:'Thermodynamics',prompt:'Find entropy'}));
assert.equal(audit.before.schoolMathsMock-audit.after.schoolMathsMock,1);
assert(sw.includes('v188-school-pure-correction'));
console.log('PASS v188: A-level contradiction retained outside 128-question first AS Pure Maths mock');