'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const read=p=>fs.readFileSync(p,'utf8');
const deck=JSON.parse(read('deck.json'));
const rates=JSON.parse(read('chemistry_rates_rp7_recall_v210.json'));
const report=JSON.parse(read('editorial/task1-v217-chemistry-legacy-recall-fixes.json'));
const app=read('app.js'),html=read('index.html'),sw=read('sw.js');
const start=app.indexOf('/* v217 legacy chemistry corrections start */');
const end=app.indexOf('/* v217 legacy chemistry corrections end */');
assert(start>=0&&end>start,'Source of runtime correction function missing');
const apply=vm.runInNewContext(app.slice(start,end)+'\napplyV217LegacyChemistryCorrections;');
assert.equal(typeof apply,'function');
assert(app.includes('cards=applyV217LegacyChemistryCorrections((d.cards||[]).filter(c=>c.active!==false));'));
assert(html.includes('app.js?v=203'),'Keep existing script URL for legacy regression and network-first service worker');
assert(sw.includes('v217-chemistry-legacy-recall-fixes'),'Offline cache version was not bumped');
assert(sw.includes("u.pathname.endsWith('/app.js')"),'App updates must remain network-first');
assert(app.includes("PROGRESS_KEY='revisionLoopProgress5'"));
assert(app.includes("PROFILE_KEY='revisionLoopProfile11'"));
assert(app.includes("SETTINGS_KEY='revisionLoopSettings11'"));
assert.equal(deck.cards.length,3345,'Historic source deck count changed');
const orig=deck.cards;
const corrected=apply(orig.map(c=>({...c})));
assert.equal(corrected.length,orig.length);
assert.deepEqual(corrected.map(c=>c.id),orig.map(c=>c.id));
assert.equal(new Set(corrected.map(c=>c.id)).size,3345);
const changed=corrected.filter((c,i)=>JSON.stringify(c)!==JSON.stringify(orig[i])).map(c=>c.id).sort();
assert.deepEqual(changed,[
 'chem_arrhenius_001','chem_cip','chem_kp_recap_20261024_pressure_position'
].sort(),'Only the three reviewed legacy cards may change');
const get=id=>corrected.find(c=>c.id===id);
const a=get('chem_arrhenius_001');
assert.equal(a.back,'Kelvin (K).');
assert.match(a.front,/which unit must T be measured/i);
assert(a.strictRecall===true&&a.accept.includes('Kelvin'));
assert.deepEqual(JSON.parse(JSON.stringify(a.concepts)),[['kelvin']]);
assert(!/gradient.*intercept/i.test(a.front),'Old multi-part prompt leaked');
assert(rates.cards.some(c=>c.front.includes('gradient of a graph of ln k')&&c.back.includes('−Ea/R')));
assert(rates.cards.some(c=>c.front.includes('vertical intercept')&&c.back.includes('ln A')));
const cip=get('chem_cip');
assert.equal(cip.topic,'E/Z isomerism');
assert.equal(cip.revisionTopic,'E/Z isomerism');
assert.equal(cip.specRef,'3.3.1.3');
assert.equal(cip.id,'chem_cip');
const kp=get('chem_kp_recap_20261024_pressure_position');
assert(kp.front.includes('different total gas mole coefficients'));
assert(kp.front.includes('constant temperature'));
assert.equal(kp.back,'The side with fewer moles of gas.');
assert(kp.strictRecall===true&&kp.accept.some(s=>s.includes('fewer')));
assert(get('task1_chem_056').back.includes('equal numbers of gas molecules'),'Equal-mole exception lost');
assert(rates.cards.some(c=>c.front.includes('what happens to the value of Kp')&&c.back.includes('unchanged')));
assert.equal(report.version,'v217');
assert.equal(report.task1Complete,false);
assert.equal(report.modifiedCoreDeck,false);
assert.deepEqual(report.correctedIDs.slice().sort(),changed);
console.log('PASS v217: three audited legacy Chemistry cards corrected at load, single-point Arrhenius recall, CIP/E-Z topic, pressure qualification; stable core IDs/progress and cache version');
