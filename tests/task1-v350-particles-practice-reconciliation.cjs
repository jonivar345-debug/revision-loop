'use strict';
// v350: verify three later Physics Particles application questions close only the specified older audit gaps.
const assert=require('node:assert/strict'),fs=require('node:fs');
const text=p=>fs.readFileSync(p,'utf8'),data=p=>JSON.parse(text(p));
const history=data('editorial/task1-v341-current-science-application-evidence.json');
const latest=data('editorial/task1-v350-particles-practice-reconciliation.json');
const bank=data('physics_particles_three_application_gaps_v342.json');
const app=text('app.js'),sw=text('sw.js');
assert.equal(latest.version,'v350');
assert.equal(latest.historicalAudit,'editorial/task1-v341-current-science-application-evidence.json');
assert.equal(latest.laterBank,'physics_particles_three_application_gaps_v342.json');
assert.equal(history.counts.physicsSelectedHistoricalGaps,9);
assert.equal(history.counts.physicsRowsWithRepresentativeManualPractice,6);
assert.equal(history.counts.physicsRowsStillWithoutVerifiedLinkedFullExamPractice,3);
const originalMissing=history.physicsSelected.filter(x=>!(x.linkedCurrentExamPractice||[]).length);
assert.deepEqual(originalMissing.map(x=>x.sourceRequirement),[6,44,48]);
assert.equal(latest.selectedPhysicsRows,9);
assert.equal(latest.oldPracticeLinkedPhysicsRows,6);
assert.equal(latest.nowPracticeLinkedPhysicsRows,9);
assert.equal(latest.allPhysicsRequirementsCertified,false);
assert.equal(latest.studentWorkingIndependentlyMarked,false);
assert.equal(latest.linkedWrittenMarksAdded,20);
assert.equal(latest.links.length,3);
assert.equal(bank.questions.length,3);
const appPaths=[...app.match(/const EXTRA_PRACTICE_URLS=\[([^\]]+)\];/)[1].matchAll(/'\.\/([^']+\.json)'/g)].map(x=>x[1]);
assert(appPaths.includes(latest.laterBank),'Particle practice must actually be loaded for exams');
assert(sw.includes("'./physics_particles_three_application_gaps_v342.json'"),'Offline cache must include particle practice');
let total=0;
for(const row of latest.links){
 const matching=originalMissing.find(x=>x.sourceRequirement===row.sourceRequirement);
 assert(matching,'Do not falsely claim a different historical gap was resolved');
 assert.equal(matching.specRef,row.specRef);
 assert.equal(row.skillId,'v263_ParticlesRequirement'+String(row.sourceRequirement).padStart(2,'0'));
 assert.equal(row.sourcePath,latest.laterBank);
 assert.equal(row.requiresManualReview,true);
 const q=bank.questions.find(x=>x.id===row.questionId);
 assert(q,'The proposed linked application question does not exist');
 assert.equal(q.subject,'Physics');
 assert.equal(q.level,'AS');
 assert.equal(q.specRef,row.specRef);
 assert.equal(q.mock,true);
 assert.equal(q.taught,true);
 assert.equal(q.skillId,row.skillId);
 assert.equal(q.marks,row.marks);
 assert.equal(q.requiresWorking,true);
 assert.equal(q.manualWorkingReview,true);
 assert.equal(q.sourceVerified,false,'Original exam-style question must not masquerade as an actual AQA past-paper question');
 assert.equal(q.markPoints.length,q.marks);
 assert.equal(q.markPointMarks.reduce((a,b)=>a+b,0),q.marks);
 total+=q.marks;
}
assert.equal(total,20);
assert.equal(history.counts.physicsRowsWithRepresentativeManualPractice+latest.links.length,9);
console.log('PASS v350: 3 historical Physics application evidence gaps now linked to loaded v342 20-mark practice, while dated v341 snapshot, source verification and manual marking caveats remain intact.');
