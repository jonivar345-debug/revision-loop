'use strict';
// Keep historical evidence immutable. Apply only explicitly reviewed corrections
// from v154, v172, v176, v177, v178, v179, v180, v181, v182, v183 v184 and v228 when comparing old snapshots with current cards.
const v154=require('../editorial/task1-v154-mock-aqa-terminology-audit.json');
const v172=require('../editorial/task1-v172-science-mock-review.json');
const v176=require('../editorial/task1-v176-mechanics-manual-spec-audit.json');
const v177=require('../editorial/task1-v177-chemistry-legacy-tests-definitions.json');
const v178=require('../editorial/task1-v178-chemistry-core-definitions.json');
const v179=require('../editorial/task1-v179-chemistry-organic-physical-audit.json');
const v180=require('../editorial/task1-v180-born-haber-gibbs-short-recall.json');
const v181=require('../editorial/task1-v181-science-210-legacy-answer-audit.json');
const v182=require('../editorial/task1-v182-220-physics-chemistry-precision.json');
const v183=require('../editorial/task1-v183-bonding-86-precision.json');
const v184=require('../editorial/task1-v184-final-172-science-legacy-audit.json');
const v228=require('../editorial/task1-v228-legacy-corrections.json');
const corrections=new Map(v154.changes.editedCards.map(row=>[row.id,row]));
const shortCards=new Map(v172.edited.map(row=>[row.id,row]));
const preciseMechanics=new Map(v176.corrections.map(row=>[row.id,row]));
const preciseChemistry=new Map(v177.corrections.map(row=>[row.id,row]));
const refinedChemistry=new Map(v178.corrections.map(row=>[row.id,row]));
const nextChemistry=new Map(v179.corrections.map(row=>[row.id,row]));
const bornHaberChemistry=new Map(v180.corrections.map(row=>[row.id,row]));
const moreScience=new Map(v181.corrections.map(row=>[row.id,row]));
const newerScience=new Map(v182.corrections.map(row=>[row.id,row]));
const finalBonding=new Map(v183.corrections.map(row=>[row.id,row]));
const finalLegacyScience=new Map(v184.corrections.map(row=>[row.id,row]));
const newlyReviewed=new Map(v228.corrections.map(row=>[row.id,row]));
module.exports=function expectedAfterReviewedEdits(id,field,historical){
 const current=newlyReviewed.get(id);
 if(current&&field==='front')return current.newFront;
 if(current&&field==='back')return current.newBack;
 const updated184=finalLegacyScience.get(id);
 if(updated184&&field==='front')return updated184.newFront;
 if(updated184&&field==='back')return updated184.newBack;
 const updated=finalBonding.get(id);
 if(updated&&field==='front')return updated.newFront;
 if(updated&&field==='back')return updated.newBack;
 const newestScience=newerScience.get(id);
 if(newestScience&&field==='front')return newestScience.newFront;
 if(newestScience&&field==='back')return newestScience.newBack;
 const latestScience=moreScience.get(id);
 if(latestScience&&field==='front')return latestScience.newFront;
 if(latestScience&&field==='back')return latestScience.newBack;
 const newest=bornHaberChemistry.get(id);
 if(newest&&field==='front')return newest.newFront;
 if(newest&&field==='back')return newest.newBack;
 const moreChem=nextChemistry.get(id);
 if(moreChem&&field==='front')return moreChem.newFront;
 if(moreChem&&field==='back')return moreChem.newBack;
 const latestChem=refinedChemistry.get(id);
 if(latestChem&&field==='front')return latestChem.newFront;
 if(latestChem&&field==='back')return latestChem.newBack;
 const chemistry=preciseChemistry.get(id);
 if(chemistry&&field==='front')return chemistry.newFront;
 if(chemistry&&field==='back')return chemistry.newBack;
 const revised=preciseMechanics.get(id);
 if(revised&&field==='back')return revised.after;
 const latest=shortCards.get(id);
 if(latest&&field==='front')return latest.newFront;
 if(latest&&field==='back')return latest.newBack;
 const prior=corrections.get(id);
 return prior&&Object.prototype.hasOwnProperty.call(prior,field)?prior[field]:historical;
};
